def _ci_table(ci: pd.DataFrame) -> pd.DataFrame:
    if ci.empty:
        return ci
    ci = ci.copy()
    ci["95% CI"] = ci.apply(lambda r: f"[{r['lower']:.4f}, {r['upper']:.4f}]", axis=1)
    return ci[["model", "metric", "point", "95% CI", "reps"]]


