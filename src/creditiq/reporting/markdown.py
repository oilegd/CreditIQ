def _fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        if math.isnan(value):
            return "-"
        if abs(value) >= 1000:
            return f"{value:,.0f}"
        return f"{value:.{digits}f}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def md_table(df: pd.DataFrame, digits: int = 4, index: bool = False) -> str:
    """Render a DataFrame as a GitHub-flavoured Markdown table (no extra dependency)."""
    if index:
        df = df.reset_index()
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = [
        "| " + " | ".join(_fmt(v.item() if hasattr(v, "item") else v, digits) for v in row) + " |"
        for row in df.itertuples(index=False, name=None)
    ]
    return "\n".join([header, sep, *rows])


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.strip() + "\n", encoding="utf-8")
    return path


# ------------------------------------------------------------------ dictionary
def write_data_dictionary(
    path: Path,
    quality: pd.DataFrame,
    catalog: Mapping[str, Mapping[str, Any]],
    feature_sets: Mapping[str, Sequence[str]],
    source: Mapping[str, Any],
) -> Path:
    rows = []
    for col, q in quality.iterrows():
        meta = catalog.get(col, {"category": "UNCLASSIFIED", "rationale": ""})
        used = [name for name, cols in feature_sets.items() if col in cols]
        rows.append(
            {
                "column": col,
                "inferred_type": q["dtype"],
                "missing_%": q["pct_missing"],
                "unique": int(q["n_unique"]),
                "min": q.get("min"),
                "max": q.get("max"),
                "availability": meta["category"],
                "modelling_use": ", ".join(used) if used else "excluded",
                "notes": meta["rationale"],
            }
        )
    table = pd.DataFrame(rows)
    text = f"""
# Data dictionary

{DISCLAIMER}

Generated by `scripts/inspect_data.py` on {date.today().isoformat()} from the **actual source file**.

| Property | Value |
| --- | --- |
| File | `{source.get("file")}` |
| Sheet(s) | {source.get("sheets")} |
| Rows x columns | {source.get("n_rows"):,} x {source.get("n_columns")} |
| SHA-256 | `{source.get("sha256")}` |
| MD5 (matches Figshare `computed_md5` if equal to 244d12efa7b8c845263bf26b0d49ae7f) | `{source.get("md5")}` |

Source: {DATASET_CITATION}.

Types are as parsed by pandas/openpyxl from the workbook. Percent-like fields
(`int_rate`, `revol_util`) are stored as fractions (0.1242 = 12.42%).
`availability` is the feature-availability audit category (see
[leakage_audit.md](leakage_audit.md)); `modelling_use` lists the feature sets that use
the column as a raw input.

{md_table(table, digits=3)}
"""
    return _write(path, text)


# ------------------------------------------------------------------ leakage audit
def write_leakage_audit(
    path: Path,
    audit: pd.DataFrame,
    screen: pd.DataFrame | None,
    feature_set_descriptions: Mapping[str, str],
) -> Path:
    counts = audit["category"].value_counts().rename_axis("category").reset_index(name="n_columns")
    sets_md = "\n".join(f"* **{k}** - {v}" for k, v in feature_set_descriptions.items())
    screen_md = (
        "Not yet computed - run `python scripts/prepare_data.py`."
        if screen is None or screen.empty
        else md_table(screen.head(25), digits=3)
    )
    text = f"""
# Feature leakage audit

{DISCLAIMER}

## Prediction point

The intended decision point is **underwriting of a new application**. A feature is
eligible only if its value would be known at that moment. Lending Club's export does
not include application timestamps; the issue month (`issue_d`) is used as the closest
available reference date (for credit-history length and out-of-time splitting).

## Categories

| Category | Meaning | Allowed in models? |
| --- | --- | --- |
| pre_underwriting | Supplied by the applicant or the credit bureau before a decision | yes |
| at_origination | Produced by Lending Club's own assessment/pricing (grade, rate, instalment, listing) | origination model only |
| uncertain | Timing not documented in this export | only when explicitly allow-listed |
| outcome_derived | Repayment, recovery or other post-origination information | **never** |
| sensitive | Free text or geography that can identify people or proxy protected traits | **never** |
| identifier_metadata | IDs, URLs, constants, split dates | **never** |

{md_table(counts)}

## Feature sets

{sets_md}

The **applicant** model is the primary portfolio model. The **origination** model is
clearly labelled: it consumes Lending Club's own grade and interest rate, which already
encode Lending Club's risk assessment, so it answers a different question ("how much
does the platform's grade add?") and must not be presented as a pre-approval model.

## Column-by-column decisions

{md_table(audit)}

## Empirical leakage screen (training split)

Single-column ROC-AUC against the target. `separation` = 2 x |AUC - 0.5|. Outcome-derived
fields separate classes almost perfectly, which confirms they must be excluded. This
screen is descriptive and only supports the documented reasoning above; a low score
does not make a column safe.

{screen_md}

## Automated guards

1. `creditiq.features.leakage_checks.check_feature_inputs` rejects any feature-set input
   whose audit category is not allowed for that set, or that is not classified at all.
2. A hard-coded deny-list (`KNOWN_LEAKAGE_COLUMNS`) rejects known Lending Club outcome fields
   even if the YAML catalogue is edited incorrectly.
3. `FeatureBuilder` re-checks at fit time; inference coerces inputs to the saved training
   schema and drops all other columns, so outcome fields cannot reach a model.
4. `tests/test_leakage.py` asserts all of the above.
"""
    return _write(path, text)


def _row(df: pd.DataFrame | None, **match: str) -> pd.Series | None:
    if df is None or df.empty:
        return None
    m = pd.Series(True, index=df.index)
    for col, prefix in match.items():
        m &= df[col].astype(str).str.startswith(prefix)
    return df[m].iloc[0] if m.any() else None


def bias_paragraph(r: Mapping[str, Any]) -> str:
    """Generated statement of how excluding unresolved loans affects the headline metrics."""
    sel = r["metadata"]["selected_model"]
    b = r.get("unresolved_bounds")
    rep = _row(b, model=sel, scenario="reported")
    real = _row(b, model=sel, scenario="Current/Grace")
    allrep = _row(b, model=sel, scenario="all unresolved repaid")
    ext = _row(b, model=sel, scenario="all unresolved adverse")
    s36 = _row(r.get("sensitivity_36_month"), model=sel, population="36")
    if rep is None or real is None or allrep is None or ext is None or s36 is None:
        return "Unresolved-loan sensitivity not available (re-run scripts/evaluate_model.py)."

    def _direction(obs: float, pred: float) -> str:
        return "over-predicted" if pred > obs else "under-predicted"

    return (
        f"{int(real['n_unresolved_added']):,} loans issued in the test window were excluded as "
        f"unresolved (concentrated in 2014 60-month vintages); their true outcomes are unknown. "
        f"They are survivors at the snapshot, so excluding them enriches the remaining 60-month "
        f"loans with charge-offs. Scoring them with the selected model ({sel}) and adding them "
        f"back under **assumed** labels (hypothetical scenarios, not observed outcomes):\n\n"
        f"* assumed: Current/Grace repaid, Late adverse - ROC-AUC **{real['roc_auc']:.4f}** "
        f"(reported {rep['roc_auc']:.4f}); scenario adverse rate {real['prevalence']:.4f} vs mean "
        f"calibrated prediction {real['mean_predicted']:.4f}; 60-month loans: scenario rate "
        f"{real['prevalence_60m']:.4f} vs predicted {real['mean_predicted_60m']:.4f};\n"
        f"* assumed: all unresolved repaid - ROC-AUC {allrep['roc_auc']:.4f};\n"
        f"* extreme bound (all unresolved adverse - implausible): ROC-AUC {ext['roc_auc']:.4f}.\n\n"
        f"On fully resolved 36-month loans (no exclusion bias, observed outcomes) the ROC-AUC is "
        f"**{s36['roc_auc']:.4f}** with mean prediction {s36['mean_predicted']:.4f} vs observed "
        f"{s36['prevalence']:.4f}.\n\n"
        f"**Interpretation:** the reported test ROC-AUC ({rep['roc_auc']:.4f}) is likely optimistic: "
        f"both plausible scenarios give lower values ({allrep['roc_auc']:.3f}-{real['roc_auc']:.3f}); "
        f"only the implausible all-adverse bound is higher. The true value cannot be computed from "
        f"this snapshot. On the reported test set 60-month loans appear "
        f"{_direction(rep['prevalence_60m'], rep['mean_predicted_60m'])} (observed "
        f"{rep['prevalence_60m']:.3f} vs predicted {rep['mean_predicted_60m']:.3f}); under the "
        f"assumed scenario they would be "
        f"{_direction(real['prevalence_60m'], real['mean_predicted_60m'])} (scenario rate "
        f"{real['prevalence_60m']:.3f} vs predicted {real['mean_predicted_60m']:.3f}). The "
        f"calibrator was fitted on 2014 Q2, which shares the same exclusion bias."
    )


def explainability_section(r: Mapping[str, Any]) -> str:
    agr = r.get("explainer_agreement")
    if agr is None or agr.empty:
        return "Not generated - run scripts/generate_reports.py."
    parts = []
    for model in dict.fromkeys(agr["model"]):
        g = agr[agr["model"] == model]
        corr = g[["rank_shap", "rank_pfi", "rank_lime"]].corr(method="spearman")
        lime = r.get(f"lime_global_{model}")
        r2 = (
            float(lime["mean_local_r2"].iloc[0])
            if lime is not None and "mean_local_r2" in lime
            else float("nan")
        )
        grouped = r.get(f"pfi_grouped_{model}")
        top_groups = (
            ", ".join(grouped.head(4)["feature"])
            if grouped is not None and not grouped.empty
            else "-"
        )
        parts.append(
            f"**{model}** - top raw inputs by mean rank across SHAP/PFI/LIME: "
            f"{', '.join(g.nsmallest(6, 'mean_rank')['feature'])}. Rank correlations: "
            f"SHAP-PFI {corr.loc['rank_shap', 'rank_pfi']:.2f}, SHAP-LIME {corr.loc['rank_shap', 'rank_lime']:.2f}, "
            f"PFI-LIME {corr.loc['rank_pfi', 'rank_lime']:.2f}. Mean LIME local R2 = {r2:.2f}. "
            f"Top grouped-PFI groups (ROC-AUC): {top_groups}.\n\n"
            + md_table(
                g.nsmallest(10, "mean_rank")[
                    [
                        "feature",
                        "mean_abs_shap",
                        "roc_auc_drop_mean",
                        "mean_abs_lime_weight",
                        "rank_shap",
                        "rank_pfi",
                        "rank_lime",
                    ]
                ]
            )
        )
    return "\n\n".join(parts)


def tda_section(r: Mapping[str, Any]) -> str:
    nodes = r.get("tda_nodes_default")
    ideas = r.get("tda_ideas_default")
    pers = r.get("tda_persistence_summary")
    if nodes is None or nodes.empty:
        return "Not generated - run scripts/generate_reports.py."
    big = nodes[nodes["size"] >= 60]
    lines = [
        f"Default Mapper graph (validation split, lens = calibrated PD): {len(nodes)} nodes; "
        f"node calibration gaps range from {big['calibration_gap'].min():+.3f} to "
        f"{big['calibration_gap'].max():+.3f} (nodes with >= 60 loans)."
    ]
    if ideas is not None and not ideas.empty:
        lines.append("\nEvidence-based ideas generated from this graph:\n")
        lines += [
            f"* **{k}** - {t}. {e}"
            for k, t, e in ideas[["kind", "title", "evidence"]].itertuples(index=False)
        ]
    if pers is not None and not pers.empty:
        lines.append("\nPersistent homology (adverse vs repaid samples):\n\n" + md_table(pers))
    return "\n".join(lines)


